def test_the_cohort_name_is_on_every_ledger_line_and_absence_means_the_baseline(
    tmp_path: Path,
) -> None:
    """The 72 recorded lines predate the key. A trial built without one is the baseline's, and
    a trial built with one carries it, so the two readings of a line cannot disagree."""
    assert _trial().cohort == BASELINE_COHORT_NAME
    assert _trial().record()["cohort"] == BASELINE_COHORT_NAME
    assert _trial().record()["refused"] == 0
    other = dataclasses.replace(_trial(), cohort="seam-other", refused=4)
    at = dt.datetime(2026, 10, 25, tzinfo=dt.UTC)

    legacy = {k: v for k, v in _trial().record().items() if k not in ("cohort", "refused")}
    ledger = tmp_path / TRIAL_LEDGER
    ledger.parent.mkdir(parents=True)
    ledger.write_text(json.dumps({"at": at.isoformat(), **legacy}) + "\n", encoding="utf-8")
    append_trials([_trial(), other], root=tmp_path, at=at, sha="abc", dirty=False)

    lines = [json.loads(line) for line in ledger.read_text(encoding="utf-8").splitlines()]
    assert count_trials(tmp_path) == 3
    assert "cohort" not in lines[0], "the legacy line was rewritten"
    assert [line.get("cohort", BASELINE_COHORT_NAME) for line in lines] == [
        BASELINE_COHORT_NAME,
        BASELINE_COHORT_NAME,
        "seam-other",
    ]
    assert lines[2]["refused"] == 4


