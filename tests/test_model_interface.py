def _drive(
    toy: Toy, cohort: Cohort, lines: list[Trial], **overrides: object
) -> wf.ConfigurationOutcome:
    def append(trials: Sequence[Trial]) -> int:
        lines.extend(trials)
        return len(trials)

    arguments: dict[str, object] = {
        "calendar": get_calendar(toy.settings),
        "first": toy.origins[0],
        "last": toy.origins[-1],
        "every": toy.stride,
        "minimum_training": toy.minimum_training,
        "cohort": cohort,
        "persisted": lambda: None,
        "append": append,
        "report": lambda _: None,
        **overrides,
    }
    return wf.run_configuration(
        toy.settings,
        "SPY",
        toy.horizon,
        toy.panel,
        toy.targets,
        **arguments,  # type: ignore[arg-type]
    )


def test_the_driver_appends_one_line_per_trial_labelled_with_the_cohort() -> None:
    toy = make_toy(1)
    lines: list[Trial] = []
    outcome = _drive(toy, Cohort("seam-driver", (Spy("alpha"), Spy("beta"))), lines)
    assert not outcome.refused and not outcome.disagrees
