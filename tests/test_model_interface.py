def test_a_view_holds_only_what_is_knowable_at_its_origin() -> None:
    """Checked on the data each contestant was handed, not on the code that made it."""
    toy = make_toy(5)
    spy = Spy()
    run_cohort(toy, Cohort("seam-views", (spy,)))
    assert spy.views
    for view in spy.views:
        assert view.symbol == "SPY" and view.horizon == 5
        assert view.response == target_column(5)
        assert view.minimum_training == toy.minimum_training and view.stride == toy.stride
        # Every training target had completed by the origin, and says when.
        assert not view.training.empty
