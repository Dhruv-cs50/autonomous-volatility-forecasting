def test_forcing_the_smearing_factor_still_reaches_the_baseline_cohort(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """``tools/measure_calibration.py`` produces the uncorrected row quoted in R73 by assigning
    ``wf.fit_ols`` by module attribute. The adapters must therefore resolve it at call time.

    A red case and not a smoke test: the patch has to *change* ``har_semilog``'s forecast and
    leave the two that do not use the smearing factor alone. An adapter that had captured
    ``fit_ols`` at import would pass every other test in this file and fail this one.
    """
    toy = make_toy(1)
    normal = run_cohort(toy, BASELINE_COHORT)
    original = wf.fit_ols

    def forced(frame: pd.DataFrame, regressors: Sequence[str], response: str) -> wf.Fit:
        return dataclasses.replace(original(frame, regressors, response), smearing=1.0)

    monkeypatch.setattr(wf, "fit_ols", forced)
    flat = run_cohort(toy, BASELINE_COHORT)

    assert _forecasts(flat, ("har_levels",)) == _forecasts(normal, ("har_levels",))
    assert _forecasts(flat, ("random_walk",)) == _forecasts(normal, ("random_walk",))
    assert _forecasts(flat, ("har_semilog",)) != _forecasts(normal, ("har_semilog",))
    for left, right in zip(normal.results, flat.results, strict=True):
        assert left.forecasts["har_semilog"] > right.forecasts["har_semilog"], left.origin


