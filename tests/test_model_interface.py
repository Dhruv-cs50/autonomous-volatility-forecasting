def test_the_conformance_suite_can_fail(monkeypatch: pytest.MonkeyPatch) -> None:
    """A suite that no model can fail proves nothing. A contestant that lies about its fit, and
    one that peeks at the target, are each caught by the clause meant for them."""
    toy = make_toy(1)

    class Peeks:
        """Claims a horizon-free fit but reads ``view.horizon``."""

        name = "peeks"
        fit_depends_on_horizon = False

        def fit(self, view: TrainingView) -> Forecaster:
            return Answer(1e-4 * view.horizon)

    with pytest.raises(AssertionError, match="horizon-free fit"):
        clause_6_horizon_contract(Peeks(), toy)

    class Coin:
        name = "coin"
        fit_depends_on_horizon = False

        def __init__(self) -> None:
            self.calls = 0

        def fit(self, view: TrainingView) -> Forecaster:
            self.calls += 1
            return Answer(1e-4 * self.calls)

    with pytest.raises(AssertionError, match="from the same view"):
        clause_5_determinism(Coin(), toy)

    class Future:
        """Forecasts the latest training target it was handed -- the realized future, if the
        harness leaks it."""

        name = "future"
        fit_depends_on_horizon = False

        def fit(self, view: TrainingView) -> Forecaster:
            return Answer(float(view.training[view.response].iloc[-1]))

    # Honest harness: the latest knowable target is the same with or without the future present.
    clause_2_target_side_equivalence(Future(), toy)
    # With the wrong slice planted by name, it is not -- and the clause says so.
    monkeypatch.setattr(wf, "knowable_targets", lambda targets, origin: targets)
    with pytest.raises(AssertionError, match="future present|whether the origin"):
        clause_2_target_side_equivalence(Future(), toy)
