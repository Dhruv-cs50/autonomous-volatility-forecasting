def test_adding_a_contestant_cannot_change_a_baseline_forecast() -> None:
    """Every individual forecast is bit-identical with a fourth contestant present. The trials
    are *not* promised to be: a refusing fourth contestant removes the origin from the comparable
    set of all four, which is R86's whole point and is asserted below rather than hidden."""
    toy = make_toy(1)
    alone_run = run_cohort(toy, BASELINE_COHORT)
    refused_at = alone_run.results[2].origin
    extra = Spy("fourth", skip_on=frozenset({refused_at}))
    wider = run_cohort(toy, Cohort("seam-wider", (*BASELINE_COHORT.models, extra)))

    assert _forecasts(wider, MODELS) == _forecasts(alone_run, MODELS)
    assert [r.training_rows for r in wider.results] == [r.training_rows for r in alone_run.results]

    before = {(t.model, t.loss): t for t in alone_run.trials()}
    after = {(t.model, t.loss): t for t in wider.trials()}
    for loss in LOSSES:
        assert after[("har_semilog", loss)].origins == before[("har_semilog", loss)].origins - 1
        assert after[("har_semilog", loss)].dropped == before[("har_semilog", loss)].dropped + 1
    assert after[("fourth", "mse")].refused == 1
    assert after[("har_semilog", "mse")].refused == 0


def test_comparable_intersects_over_the_cohort_and_not_the_global_tuple(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    toy = make_toy(1)
    pair = Cohort("seam-pair", (Spy("alpha", value=2e-4), Spy("beta", value=3e-4)))
    clean = run_cohort(toy, pair)
    assert clean.comparable("mse") == {result.origin for result in clean.results}
    assert clean.contestants == ("alpha", "beta")

    # Planting a name in the global changes nothing about a cohort run...
    monkeypatch.setattr(wf, "MODELS", (*MODELS, "ghost"))
    planted = run_cohort(toy, pair)
    assert planted.comparable("mse") == clean.comparable("mse")
    assert [t.value for t in planted.trials()] == [t.value for t in clean.trials()]
    # ...and the evaluation does not look the name up at all, so no KeyError on 'ghost'.
    assert "ghost" not in planted.results[0].forecasts


