def test_a_model_skip_is_recorded_against_the_model_and_leaves_the_origin() -> None:
    """R87. A model's own refusal must not be filed as a window problem."""
    toy = make_toy(1)
    reference = run_cohort(toy, BASELINE_COHORT)
    declined = reference.results[1].origin
    spy = Spy("picky", skip_on=frozenset({declined}))
    evaluation = run_cohort(toy, Cohort("seam-skip", (*BASELINE_COHORT.models, spy)))

    assert [result.origin for result in evaluation.results] == [
        result.origin for result in reference.results
    ], "a model's refusal removed an origin from everyone"
    assert evaluation.refusals == ((declined, "picky", f"declined {declined}"),)
    at = next(result for result in evaluation.results if result.origin == declined)
    assert math.isnan(at.forecasts["picky"])
    assert not math.isnan(at.forecasts["har_levels"])
    assert evaluation.skipped == reference.skipped
    # ...and the origin leaves the comparison for everyone, on both losses.
    assert declined not in evaluation.comparable("mse")
    assert declined not in evaluation.comparable("qlike")


