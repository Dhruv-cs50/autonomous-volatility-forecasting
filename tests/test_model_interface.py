GOLDENS = Path(__file__).parent / "goldens" / "baseline_toy_forecasts.json"
GOLDEN_HORIZONS = (1, 5)


def _hex(value: float) -> str:
    """Exact text for a float: ``float.hex`` keeps ``-0.0`` and every last bit, and spells NaN."""
    return float(value).hex()


def capture(toy: Toy) -> dict[str, object]:
    """Everything the baseline cohort produced on ``toy``, as exactly comparable text.

    Deliberately uses only the walk-forward's original surface -- default ``evaluate``,
    ``results``, ``skipped`` and ``trials()`` -- because the goldens were captured on the code
    from before the seam existed and this function had to run there too. Skip *reasons* are left
    out, since the refactor reworded one; the skipped *origins* are in.
    """
    evaluation = evaluate(
        toy.panel,
        toy.targets,
        toy.origins,
        symbol="SPY",
        horizon=toy.horizon,
        calendar=get_calendar(toy.settings),
        minimum_training=toy.minimum_training,
    )
    return {
        "requested": evaluation.requested,
        "skipped": [origin.isoformat() for origin, _ in evaluation.skipped],
        "results": [
            {
                "origin": result.origin.isoformat(),
                "realized": _hex(result.realized),
                "training_rows": result.training_rows,
                "forecasts": {name: _hex(value) for name, value in result.forecasts.items()},
            }
            for result in evaluation.results
        ],
        "trials": [
            {
                "model": trial.model,
                "loss": trial.loss,
                "origins": trial.origins,
                "dropped": trial.dropped,
                "value": _hex(trial.value),
            }
            for trial in evaluation.trials()
        ],
    }


@pytest.mark.parametrize("horizon", GOLDEN_HORIZONS)
def test_the_baseline_cohort_reproduces_the_committed_goldens(horizon: int) -> None:
    """R86's first witness. ``==`` on hex text, never ``approx``: a forecast that moved in its
    last bit is a forecast that moved. The file is not regenerated by any switch here, so a
    changed number is a changed experiment and has to be argued for in a diff."""
    recorded = json.loads(GOLDENS.read_text(encoding="utf-8"))
    assert capture(make_toy(horizon)) == recorded[f"h{horizon}"]


